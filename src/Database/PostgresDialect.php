<?php

declare(strict_types=1);

namespace App\Database;

use RuntimeException;

final class PostgresDialect
{
    public static function translate(string $sql): string
    {
        $sql = str_replace(chr(96), '"', $sql);
        $sql = preg_replace('/\bDATABASE\(\)/i', 'current_schema()', $sql) ?? $sql;
        $sql = preg_replace('/\bUTC_TIMESTAMP\(\)/i', "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC')", $sql) ?? $sql;
        $sql = preg_replace_callback('/DATE_ADD\((CURRENT_TIMESTAMP|[A-Za-z_][A-Za-z0-9_.]*),\s*INTERVAL\s+(:[A-Za-z_][A-Za-z0-9_]*|[0-9]+)\s+(SECOND|MINUTE|HOUR|DAY)\)/i',
            static function (array $m): string {
                $unit = strtolower($m[3]);
                return is_numeric($m[2]) ? '(' . $m[1] . " + INTERVAL '" . $m[2] . ' ' . $unit . "')" : '(' . $m[1] . ' + (' . $m[2] . " * INTERVAL '1 " . $unit . "'))";
            }, $sql) ?? $sql;
        $sql = preg_replace_callback('/DATE_SUB\((CURRENT_TIMESTAMP|[A-Za-z_][A-Za-z0-9_.]*),\s*INTERVAL\s+(:[A-Za-z_][A-Za-z0-9_]*|[0-9]+)\s+(SECOND|MINUTE|HOUR|DAY)\)/i',
            static function (array $m): string {
                $unit = strtolower($m[3]);
                return is_numeric($m[2]) ? '(' . $m[1] . " - INTERVAL '" . $m[2] . ' ' . $unit . "')" : '(' . $m[1] . ' - (' . $m[2] . " * INTERVAL '1 " . $unit . "'))";
            }, $sql) ?? $sql;
        $sql = preg_replace_callback("/DATE_FORMAT\(([^,]+),\s*'([^']+)'\)/i",
            static function (array $m): string {
                $format = strtr($m[2], ['%Y' => 'YYYY', '%m' => 'MM', '%d' => 'DD', '%H' => 'HH24', '%i' => 'MI', '%s' => 'SS']);
                return "TO_CHAR(" . trim($m[1]) . ", '" . $format . "')";
            }, $sql) ?? $sql;
        $sql = preg_replace('/SHOW\s+TABLES/i', "SELECT table_name FROM information_schema.tables WHERE table_schema = current_schema() ORDER BY table_name", $sql) ?? $sql;
        $sql = preg_replace_callback('/SHOW\s+COLUMNS\s+FROM\s+([A-Za-z0-9_]+)/i',
            static fn(array $m): string => "SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = '" . $m[1] . "' ORDER BY ordinal_position", $sql) ?? $sql;
        $sql = preg_replace_callback("/GET_LOCK\('([^']+)'\s*,\s*[0-9]+\)/i",
            static fn(array $m): string => "pg_try_advisory_lock(hashtext('" . str_replace("'", "''", $m[1]) . "'))", $sql) ?? $sql;
        $sql = preg_replace_callback("/RELEASE_LOCK\('([^']+)'\)/i",
            static fn(array $m): string => "pg_advisory_unlock(hashtext('" . str_replace("'", "''", $m[1]) . "'))", $sql) ?? $sql;
        if (preg_match('/INSERT\s+IGNORE\s+INTO/i', $sql)) {
            $sql = preg_replace('/INSERT\s+IGNORE\s+INTO/i', 'INSERT INTO', $sql, 1) ?? $sql;
            return rtrim(trim($sql), ';') . ' ON CONFLICT DO NOTHING';
        }
        if (preg_match('/ON\s+DUPLICATE\s+KEY\s+UPDATE/i', $sql)) {
            if (!preg_match('/INSERT\s+INTO\s+([A-Za-z0-9_]+)/i', $sql, $match)) {
                throw new RuntimeException('Could not identify the table for a legacy upsert.');
            }
            $keys = ['users' => 'telegram_user_id', 'bot_settings' => 'setting_key'];
            $table = strtolower($match[1]);
            if (!isset($keys[$table])) throw new RuntimeException('No PostgreSQL conflict key configured for ' . $table);
            $sql = preg_replace('/ON\s+DUPLICATE\s+KEY\s+UPDATE/i', 'ON CONFLICT (' . $keys[$table] . ') DO UPDATE SET', $sql, 1) ?? $sql;
            $sql = preg_replace('/VALUES\(([A-Za-z0-9_]+)\)/i', 'EXCLUDED.$1', $sql) ?? $sql;
        }
        return $sql;
    }

    /** @return list<string> */
    public static function migrationStatements(string $sql): array
    {
        $sql = trim($sql);
        $indexes = [];
        if (preg_match('/^CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z0-9_]+)/i', $sql, $match)) {
            $table = $match[1];
            $sql = preg_replace_callback('/,\s*INDEX\s+([A-Za-z0-9_]+)\s*\(([^)]+)\)/i',
                static function (array $m) use (&$indexes, $table): string {
                    $indexes[] = 'CREATE INDEX IF NOT EXISTS "' . $m[1] . '" ON "' . $table . '" (' . $m[2] . ')';
                    return '';
                }, $sql) ?? $sql;
            $sql = preg_replace('/UNIQUE\s+KEY\s+([A-Za-z0-9_]+)\s*\(([^)]+)\)/i', 'CONSTRAINT $1 UNIQUE ($2)', $sql) ?? $sql;
        }
        $sql = preg_replace('/\bBIGINT\s+UNSIGNED\b/i', 'BIGINT', $sql) ?? $sql;
        $sql = preg_replace('/\bINT\s+UNSIGNED\b/i', 'INTEGER', $sql) ?? $sql;
        $sql = preg_replace('/\bTINYINT\s*\(\s*1\s*\)/i', 'SMALLINT', $sql) ?? $sql;
        $sql = preg_replace('/\bLONGTEXT\b/i', 'TEXT', $sql) ?? $sql;
        $sql = preg_replace('/\bDATETIME\b/i', 'TIMESTAMP', $sql) ?? $sql;
        $sql = preg_replace('/\bBIGINT\s+NOT\s+NULL\s+AUTO_INCREMENT\s+PRIMARY\s+KEY/i', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', $sql) ?? $sql;
        $sql = preg_replace('/\bINTEGER\s+NOT\s+NULL\s+AUTO_INCREMENT\s+PRIMARY\s+KEY/i', 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', $sql) ?? $sql;
        $sql = preg_replace('/\s+ON\s+UPDATE\s+CURRENT_TIMESTAMP/i', '', $sql) ?? $sql;
        $sql = preg_replace('/\s+ENGINE\s*=\s*InnoDB\b[^;]*/i', '', $sql) ?? $sql;
        $sql = preg_replace('/\s+DEFAULT\s+CHARSET\s*=\s*[A-Za-z0-9_]+/i', '', $sql) ?? $sql;
        $sql = preg_replace('/\s+COLLATE\s*=\s*[A-Za-z0-9_]+/i', '', $sql) ?? $sql;
        if (preg_match('/^ALTER\s+TABLE\s+([A-Za-z0-9_]+)\s+(.*)$/is', $sql, $alter)) {
            $table = $alter[1];
            $body = preg_replace_callback('/,\s*ADD\s+INDEX\s+([A-Za-z0-9_]+)\s*\(([^)]+)\)/i',
                static function (array $m) use (&$indexes, $table): string {
                    $indexes[] = 'CREATE INDEX IF NOT EXISTS "' . $m[1] . '" ON "' . $table . '" (' . $m[2] . ')';
                    return '';
                }, $alter[2]) ?? $alter[2];
            $sql = 'ALTER TABLE "' . $table . '" ' . trim($body);
            $sql = preg_replace('/\bADD\s+(?!COLUMN\b)/i', 'ADD COLUMN ', $sql) ?? $sql;
        }
        $sql = preg_replace('/\s+/', ' ', $sql) ?? $sql;
        return array_merge([rtrim(trim($sql), ';')], $indexes);
    }
}
